-- Governance database: central home for tags, policies and other governance objects
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS GOVERNANCE COMMENT = 'Central governance: tags, policies, masking';

CREATE SCHEMA IF NOT EXISTS GOVERNANCE.TAGS COMMENT = 'Object tags for classification and chargeback';
CREATE SCHEMA IF NOT EXISTS GOVERNANCE.POLICIES COMMENT = 'Masking, row access and other security policies';

-- Tags
CREATE TAG IF NOT EXISTS GOVERNANCE.TAGS.ENVIRONMENT
    ALLOWED_VALUES 'DEV', 'QA', 'PROD', 'SHARED'
    COMMENT = 'Deployment environment of the object';

CREATE TAG IF NOT EXISTS GOVERNANCE.TAGS.DATA_LAYER
    ALLOWED_VALUES 'BRONZE', 'SILVER', 'GOLD', 'COMMON', 'GOVERNANCE'
    COMMENT = 'Medallion layer of the object';

CREATE TAG IF NOT EXISTS GOVERNANCE.TAGS.COST_CENTER
    ALLOWED_VALUES 'SALES_ANALYTICS', 'DATA_GOVERNANCE'
    COMMENT = 'Cost center for chargeback';

CREATE TAG IF NOT EXISTS GOVERNANCE.TAGS.DATA_OWNER
    COMMENT = 'Team accountable for the object';

CREATE TAG IF NOT EXISTS GOVERNANCE.TAGS.DATA_CLASSIFICATION
    ALLOWED_VALUES 'PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED'
    COMMENT = 'Sensitivity level of the data';

-- Tag the governance database and schemas
ALTER DATABASE GOVERNANCE SET TAG
    GOVERNANCE.TAGS.ENVIRONMENT = 'SHARED',
    GOVERNANCE.TAGS.COST_CENTER = 'DATA_GOVERNANCE',
    GOVERNANCE.TAGS.DATA_OWNER = 'DATA_ENGINEERING';

ALTER SCHEMA GOVERNANCE.TAGS SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'GOVERNANCE';
ALTER SCHEMA GOVERNANCE.POLICIES SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'GOVERNANCE';
