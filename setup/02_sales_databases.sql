-- Sales databases for dev / qa / prod with medallion schemas and a common utility schema
-- Dev and QA are transient (no Fail-safe cost); all schemas and tables inside inherit this.
USE ROLE ACCOUNTADMIN;

-- ---------- SALES_DEV ----------
CREATE TRANSIENT DATABASE IF NOT EXISTS SALES_DEV COMMENT = 'Sales analytics - development';

CREATE SCHEMA IF NOT EXISTS SALES_DEV.BRONZE COMMENT = 'Raw landed sales data';
CREATE SCHEMA IF NOT EXISTS SALES_DEV.SILVER COMMENT = 'Cleaned and curated sales data';
CREATE SCHEMA IF NOT EXISTS SALES_DEV.GOLD   COMMENT = 'Modelled facts, dimensions, semantic views';
CREATE SCHEMA IF NOT EXISTS SALES_DEV.COMMON COMMENT = 'File formats, sequences, UDFs, procedures';

ALTER DATABASE SALES_DEV SET TAG
    GOVERNANCE.TAGS.ENVIRONMENT = 'DEV',
    GOVERNANCE.TAGS.COST_CENTER = 'SALES_ANALYTICS',
    GOVERNANCE.TAGS.DATA_OWNER = 'DATA_ENGINEERING';

ALTER SCHEMA SALES_DEV.BRONZE SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'BRONZE';
ALTER SCHEMA SALES_DEV.SILVER SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'SILVER';
ALTER SCHEMA SALES_DEV.GOLD   SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'GOLD';
ALTER SCHEMA SALES_DEV.COMMON SET TAG GOVERNANCE.TAGS.DATA_LAYER = 'COMMON';

